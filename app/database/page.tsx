import Link from "next/link";
import { getTables, runQuery } from "@/lib/db";

const sqlLink = (q: string) => `/sql?q=${encodeURIComponent(q)}`;

// Hand-written notes for the demo dataset; tables without one still list their columns.
const ABOUT: Record<string, string> = {
  customers: "Who buys from the store. Each customer has a country and a segment (Consumer, Small Business or Enterprise).",
  products: "The catalog: 30 products in five categories, each with its list price.",
  orders: "One row per purchase: who placed it, when, and whether it was completed, cancelled or refunded.",
  order_items: "The lines of each order: which product, how many units, and the price paid per unit, which can be 10% below list price.",
};

const EXAMPLES = [
  ["Revenue by country", "SELECT c.country, ROUND(SUM(oi.quantity * oi.unit_price)) AS revenue\nFROM order_items oi\nJOIN orders o ON o.id = oi.order_id\nJOIN customers c ON c.id = o.customer_id\nWHERE o.status = 'completed'\nGROUP BY c.country\nORDER BY revenue DESC"],
  ["Best-selling products", "SELECT p.name, p.category, SUM(oi.quantity) AS units\nFROM order_items oi\nJOIN products p ON p.id = oi.product_id\nGROUP BY p.id\nORDER BY units DESC\nLIMIT 10"],
  ["Orders by status per month", "SELECT strftime('%Y-%m', order_date) AS month, status, COUNT(*) AS orders\nFROM orders\nGROUP BY month, status\nORDER BY month, status"],
];

const fmt = new Intl.NumberFormat("en-US");

export default function DatabasePage() {
  const tables = getTables();
  const [range] = runQuery("SELECT MIN(order_date) AS first, MAX(order_date) AS last FROM orders");

  return (
    <main className="mx-auto max-w-5xl space-y-10 px-4 py-8 sm:px-6">
      <section className="space-y-3">
        <h1 className="text-2xl font-semibold tracking-tight">The database</h1>
        <p className="max-w-3xl text-ink-2">
          The dashboard runs on a small SQLite database describing a fictional online store. It holds every order placed between {range.first} and{" "}
          {range.last}, with a holiday peak each November and December and steady growth over time. The data is generated by{" "}
          <code className="rounded bg-grid px-1 py-0.5 text-[13px]">scripts/seed.mjs</code> with a fixed seed, so everyone gets the same numbers.
        </p>
        <p className="max-w-3xl text-ink-2">
          The connection is read-only: the assistant, the dashboard and the <Link href="/sql" className="text-accent underline">SQL page</Link> can
          query the data but never change it.
        </p>
      </section>

      <section aria-labelledby="relations" className="space-y-3">
        <h2 id="relations" className="text-lg font-semibold">How the tables relate</h2>
        <p className="max-w-3xl text-ink-2">
          A customer places many orders, an order has many items, and each item points to one product. Revenue is{" "}
          <code className="rounded bg-grid px-1 py-0.5 text-[13px]">quantity × unit_price</code> summed over order items.
        </p>
        <ul className="space-y-1 font-mono text-[13px] text-ink-2">
          {tables.flatMap((t) =>
            t.columns.filter((c) => c.ref).map((c) => (
              <li key={t.name + c.name}>
                {t.name}.{c.name} <span className="text-muted">→</span> {c.ref}
              </li>
            )),
          )}
        </ul>
      </section>

      <section aria-labelledby="tables" className="space-y-4">
        <h2 id="tables" className="text-lg font-semibold">Tables</h2>
        <div className="grid gap-4 md:grid-cols-2">
          {tables.map((t) => (
            <article key={t.name} className="rounded-2xl border border-line bg-surface p-4">
              <header className="flex items-baseline justify-between gap-2">
                <h3 className="font-mono font-medium">{t.name}</h3>
                <span className="text-sm text-muted">{fmt.format(t.rows)} rows</span>
              </header>
              {ABOUT[t.name] && <p className="mt-1 text-sm text-ink-2">{ABOUT[t.name]}</p>}
              <table className="mt-3 w-full text-left text-sm">
                <thead className="text-ink-2">
                  <tr>
                    <th scope="col" className="border-b border-line py-1.5 font-medium">Column</th>
                    <th scope="col" className="border-b border-line py-1.5 font-medium">Type</th>
                    <th scope="col" className="border-b border-line py-1.5 font-medium">Key</th>
                  </tr>
                </thead>
                <tbody className="font-mono text-[13px]">
                  {t.columns.map((c) => (
                    <tr key={c.name} className="border-b border-line last:border-0">
                      <td className="py-1.5">{c.name}</td>
                      <td className="py-1.5 text-ink-2">{c.type}</td>
                      <td className="py-1.5 text-ink-2">{c.pk ? "primary key" : c.ref ? `→ ${c.ref}` : ""}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
              <Link href={sqlLink(`SELECT * FROM ${t.name} LIMIT 100`)} className="mt-3 inline-block text-sm text-accent underline">
                Browse rows
              </Link>
            </article>
          ))}
        </div>
      </section>

      <section aria-labelledby="examples" className="space-y-3">
        <h2 id="examples" className="text-lg font-semibold">Queries to try</h2>
        <ul className="grid gap-3 md:grid-cols-3">
          {EXAMPLES.map(([title, sql]) => (
            <li key={title}>
              <Link href={sqlLink(sql)} className="block h-full rounded-2xl border border-line bg-surface p-4 transition hover:border-accent">
                <span className="font-medium">{title}</span>
                <pre className="mt-2 overflow-hidden font-mono text-xs whitespace-pre-wrap text-ink-2">{sql}</pre>
              </Link>
            </li>
          ))}
        </ul>
      </section>
    </main>
  );
}
